def _require_known_symbol(symbol: str) -> str:
    """
    Confirm a symbol exists in the companies table before doing more
    work, so endpoints that don't otherwise distinguish "unknown symbol"
    from "known symbol, no data yet" (e.g. get_company_sentiment(),
    get_news()) can still return a proper 404 for a typo'd/unloaded
    symbol rather than a misleadingly-empty 200.

    Args:
        symbol: Stock ticker symbol as given by the caller.

    Returns:
        The symbol, uppercased.

    Raises:
        HTTPException: 404 if the symbol has no row in companies.
    """
    normalized = symbol.strip().upper()
    query = "SELECT 1 FROM companies WHERE symbol = %s;"

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(query, (normalized,))
            exists = cur.fetchone() is not None

    if not exists:
        raise HTTPException(status_code=404, detail=f"Unknown symbol: {symbol!r}")

    return normalized


