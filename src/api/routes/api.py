"""
api.py

Phase 13: dedicated JSON endpoints, off the same routes/services structure
that has served the server-rendered HTML dashboard since Phase 5 (see
src/api/main.py's module docstring). Every endpoint here is a thin
wrapper around a service/analytics function that already existed for the
dashboard — this module adds no new business logic, only JSON shaping,
request validation (src/api/schemas.py), and HTTP status codes.

Grouped per the blueprint's roadmap line for Phase 13:
    /stocks /news /company /sentiment /predict /assistant /portfolio

- /stocks, /company, /news: read-only market data (Phases 1-6).
- /sentiment: Phase 7 sentiment scoring.
- /predict: Phase 8 ML predictions + Phase 9 SHAP explanations.
- /assistant: Phase 10 AI research summaries (GET) and Phase 11's RAG
  annual-report Q&A (POST .../ask) — the first time either is reachable
  over HTTP rather than only through the dashboard page / RAG CLI.
- /portfolio: Phase 12 portfolio CRUD + analytics, as JSON instead of
  HTML forms.

All endpoints live under the `/api` prefix so they're clearly separate
from the dashboard's human-facing routes (`/`, `/stocks/{symbol}`,
`/portfolio`), which continue to return HTML unchanged. Interactive docs
for everything in this file are auto-generated by FastAPI at `/docs`.
"""

